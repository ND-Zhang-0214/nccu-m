// 示範模式開關(2026-08-31 新增)
// ─────────────────────────────────────────────────────────────
// 背景:平台原本就內建「一鍵登入」三個示範帳號(見 shared/categories.ts 的 DEMO_PERSONAS),
// 但當初的開放條件寫死為 `process.env.NODE_ENV !== "production"`。這個判斷在開發者自己的
// 電腦上是對的,可是一旦部署到託管平台(Vercel 上 next build 後必然以 NODE_ENV=production
// 執行),整組按鈕就會消失、伺服器端也一律拒絕——結果是「要拿給別人看的那個網址」反而是
// 唯一沒辦法 present 的環境,與當初做這個功能的目的完全相反。
//
// 因此改為獨立的顯式開關:預設關閉(不設就是關),要開必須自己去環境變數加一行。
// NODE_ENV 不再是判斷依據,取而代之的是「站台管理者有沒有明確表示這是示範站」。
//
// 為什麼用 NEXT_PUBLIC_ 前綴:登入頁(src/app/login/page.tsx)是 client component,
// 要決定「畫不畫那三顆按鈕」就必須在瀏覽器端讀得到這個值,而 Next.js 只會把
// NEXT_PUBLIC_ 開頭的變數內嵌進前端程式碼。伺服器端(auth.ts / actions.ts)讀同一個
// 變數名稱即可,不需要另外設第二個——少一個變數就少一種「只設了一半」的錯誤狀態。
// 這個值本身不是機密(內容就是 "1"),被打包進前端沒有安全疑慮。
//
// ⚠️ 這是刻意放寬的安全邊界,務必理解再開:
//   開啟後,任何知道網址的人都能不經驗證碼、直接以示範學生/示範教授/示範管理員的身分登入。
//   這正是「拿給人試用」需要的行為,但也代表這個站台不能放任何真實的個人資料。
//   要收掉的時候,把環境變數刪掉並重新部署即可,程式碼不用動。
//
// 注意:NEXT_PUBLIC_ 變數是「建置當下」內嵌的,不是執行時讀取。
// 在 Vercel 改完這個變數之後,一定要重新部署(Redeploy)才會生效。
export function isDemoMode(): boolean {
  return process.env.NEXT_PUBLIC_DEMO_MODE === "1";
}
